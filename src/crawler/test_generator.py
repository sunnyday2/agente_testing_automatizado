    # --- Utility Methods ---

    def _ensure_init_files(self) -> None:
        """Create __init__.py files in output directories."""
        for dir_path in (self._output_dir, self._pom_dir, self._tests_dir):
            init_file = dir_path / "__init__.py"
            if not init_file.exists():
                init_file.write_text("", encoding="utf-8")

    def _url_to_class_name(self, url: str, title: str = "") -> str:
        """Convert URL/title to a valid Python class name.

        Args:
            url: The page URL.
            title: Optional page title.

        Returns:
            PascalCase class name (e.g., LoginPage).
        """
        # Prefer title if available
        source = title if title else self._url_path(url)
        # Clean and convert to PascalCase
        cleaned = re.sub(r"[^\w\s]", " ", source)
        parts = cleaned.split()
        class_name = "".join(word.capitalize() for word in parts if word)
        if not class_name:
            class_name = "Unknown"
        return f"{class_name}Page"

    def _url_to_file_name(self, url: str, title: str = "") -> str:
        """Convert URL/title to a valid Python file name (snake_case).

        Args:
            url: The page URL.
            title: Optional page title.

        Returns:
            snake_case file name without extension.
        """
        source = title if title else self._url_path(url)
        cleaned = re.sub(r"[^\w\s]", " ", source).lower()
        parts = cleaned.split()
        file_name = "_".join(p for p in parts if p)
        return file_name or "unknown"

    def _url_to_test_name(self, url: str, title: str = "") -> str:
        """Convert URL/title to a valid pytest test function name.

        Uses the URL path to ensure uniqueness even when multiple pages
        share the same title. Falls back to title only for the root page.

        Args:
            url: The page URL.
            title: Optional page title.

        Returns:
            snake_case test name guaranteed unique per URL.
        """
        # Always derive from URL path for uniqueness
        path = self._url_path(url)
        if path and path != "/":
            # Use path: /catalogo?cat=Perros → catalogo_cat_perros
            cleaned = re.sub(r"[^\w\s]", " ", path).lower()
            parts = cleaned.split()
            name = "_".join(p for p in parts if p)
        elif title:
            # Root page: use title
            cleaned = re.sub(r"[^\w\s]", " ", title).lower()
            parts = cleaned.split()
            name = "_".join(p for p in parts if p)
        else:
            name = "home"

        # Ensure it starts with a letter
        if name and name[0].isdigit():
            name = f"page_{name}"
        return name or "unknown"

    def _element_to_attr_name(self, elem) -> str:
        """Convert an element to a Python attribute name.

        Args:
            elem: PageElement object.

        Returns:
            snake_case attribute name, or empty if cannot generate.
        """
        # Use text, aria-label, name, or type
        source = elem.text or elem.aria_label or ""
        if not source:
            # Try to extract from selector
            if "name='" in elem.selector:
                match = re.search(r"name='([^']+)'", elem.selector)
                if match:
                    source = match.group(1)
            elif "#" in elem.selector:
                source = elem.selector.lstrip("#")

        if not source:
            source = f"{elem.tag}_{elem.element_type}" if elem.element_type else elem.tag

        cleaned = re.sub(r"[^\w\s]", " ", source).lower().strip()
        parts = cleaned.split()[:4]  # Max 4 words
        name = "_".join(p for p in parts if p)
        return name or ""

    def _element_to_method_name(self, elem, prefix: str) -> str:
        """Convert an element to a Python method name.

        Args:
            elem: PageElement object.
            prefix: Method prefix (e.g., "click", "fill").

        Returns:
            snake_case method name, or empty if cannot generate.
        """
        attr_name = self._element_to_attr_name(elem)
        if not attr_name:
            return ""
        return f"{prefix}_{attr_name}"

    def _url_path(self, url: str) -> str:
        """Extract the path portion of a URL.

        Args:
            url: Full URL.

        Returns:
            The path component (e.g., "/login").
        """
        from urllib.parse import urlparse

        return urlparse(url).path or "/"

    @staticmethod
    def _has_form_elements(page: PageNode) -> bool:
        """Check if a page has form-related elements."""
        return any(
            e.tag in ("input", "textarea", "select")
            and e.element_type not in ("hidden", "submit", "button")
            for e in page.elements
        )
